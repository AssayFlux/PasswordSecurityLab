"""Heuristic password strength assessment; no password is retained."""

import math
import string


def audit_password(password: str) -> dict[str, object]:
    if not isinstance(password, str):
        raise TypeError("Password must be a string.")
    length = len(password)
    pool = sum((
        26 if any(c in string.ascii_lowercase for c in password) else 0,
        26 if any(c in string.ascii_uppercase for c in password) else 0,
        10 if any(c in string.digits for c in password) else 0,
        33 if any(c in string.punctuation for c in password) else 0,
        1 if any(c.isspace() for c in password) else 0,
    ))
    entropy = length * math.log2(pool) if pool else 0.0
    findings = []
    if length < 12:
        findings.append("Prefer at least 12 characters; longer unique passphrases are better.")
    if length and len(set(password)) <= max(1, length // 3):
        findings.append("Many characters repeat.")
    if password.isalpha() or password.isdigit():
        findings.append("Only one broad character category is used.")
    if any(x in password.lower() for x in ("password", "qwerty", "admin", "letmein")):
        findings.append("A predictable word or pattern was detected.")
    if not password:
        findings.append("No password was supplied.")
    score = int(length >= 12) + int(length >= 16) + int(pool >= 62) + int(entropy >= 60)
    if findings:
        score = min(score, 2)
    return {
        "length": length, "estimated_character_pool": pool,
        "estimated_entropy_bits": round(entropy, 2), "heuristic_score": score,
        "rating": ("weak", "fair", "good", "strong", "very strong")[score],
        "findings": findings,
        "limitations": ["Heuristic only; not a crack-time prediction.",
                        "Character-pool entropy can overestimate human-chosen passwords.",
                        "Prefer unique passwords generated by a password manager."],
    }
